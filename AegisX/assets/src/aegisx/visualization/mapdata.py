def city_by_country(code: str) -> tuple[str, float, float] | None:
    for name, lat, lon, cc in CITIES:
        if cc == code:
            return name, lat, lon
    return None


def point_in_polygon(x: float, y: float, poly: list[tuple[float, float]]) -> bool:
    """Ray-casting point-in-polygon on lon/lat plane."""
    inside = False
    n = len(poly)
    j = n - 1
    for i in range(n):
        xi, yi = poly[i]
        xj, yj = poly[j]
        if (yi > y) != (yj > y):
            x_int = (xj - xi) * (y - yi) / (yj - yi + 1e-12) + xi
            if x < x_int:
                inside = not inside
        j = i
    return inside


def is_land(lon: float, lat: float) -> bool:
    for _name, poly in LAND_POLYGONS:
        if point_in_polygon(lon, lat, poly):
            for _wn, water in WATER_OVERLAYS:
                if point_in_polygon(lon, lat, water):
                    return False
            return True
    return False
